# ---------------------------------------------------------------------------
# Markdown parsing
# ---------------------------------------------------------------------------

RE_HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
RE_LIST = re.compile(r"^(\s*)([-*]|\d+\.)\s+(.*)$")
RE_FENCE = re.compile(r"^(\s*)```")
RE_TABLE_SEP = re.compile(r"^\s*\|?\s*:?-+:?\s*(\|\s*:?-+:?\s*)*\|?\s*$")


def indent_of(line):
    return len(line) - len(line.lstrip(" "))


def is_block_start(line):
    """A line that begins something other than a paragraph."""
    return bool(RE_HEADING.match(line) or RE_LIST.match(line) or RE_FENCE.match(line)
                or line.lstrip().startswith("|"))


def parse_blocks(lines):
    """Turn lines of Markdown into a list of block dicts."""
    blocks = []
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        if not line.strip():
            i += 1
            continue

        m = RE_HEADING.match(line)
        if m:
            blocks.append({"type": "heading", "level": len(m.group(1)), "text": m.group(2)})
            i += 1
            continue

        m = RE_FENCE.match(line)
        if m:
            ind = len(m.group(1))
            i += 1
            code = []
            while i < n and not RE_FENCE.match(lines[i]):
                code.append(lines[i][ind:] if lines[i][:ind].strip() == "" else lines[i].lstrip())
                i += 1
            i += 1  # closing fence
            blocks.append({"type": "code", "text": "\n".join(code)})
            continue

        if line.lstrip().startswith("|") and i + 1 < n and RE_TABLE_SEP.match(lines[i + 1]):
            header = split_row(line)
            i += 2
            rows = []
            while i < n and lines[i].lstrip().startswith("|"):
                rows.append(split_row(lines[i]))
                i += 1
            blocks.append({"type": "table", "header": header, "rows": rows})
            continue

        m = RE_LIST.match(line)
        if m:
            list_indent = len(m.group(1))
            ordered = m.group(2)[0].isdigit()
            items = []
            while i < n:
                m = RE_LIST.match(lines[i])
                if not m or len(m.group(1)) != list_indent or (m.group(2)[0].isdigit()) != ordered:
                    break
                content_indent = list_indent + len(m.group(2)) + 1
                item_lines = [m.group(3)]
                i += 1
                while i < n:
                    cur = lines[i]
                    if not cur.strip():
                        # A blank line: the item goes on if an indented line follows.
                        j = i
                        while j < n and not lines[j].strip():
                            j += 1
                        if j < n and indent_of(lines[j]) >= content_indent:
                            item_lines.extend([""] * (j - i))
                            i = j
                            continue
                        break
                    if indent_of(cur) >= content_indent:
                        item_lines.append(cur[content_indent:])
                        i += 1
                        continue
                    # Lazy continuation of a paragraph inside the item.
                    if (not is_block_start(cur) and item_lines and item_lines[-1].strip()):
                        item_lines.append(cur.lstrip())
                        i += 1
                        continue
                    break
                items.append(parse_blocks(item_lines))
                # Skip blank lines between items of the same list.
                j = i
                while j < n and not lines[j].strip():
                    j += 1
                if j < n:
                    m2 = RE_LIST.match(lines[j])
                    if m2 and len(m2.group(1)) == list_indent and (m2.group(2)[0].isdigit()) == ordered:
                        i = j
                        continue
                break
            blocks.append({"type": "list", "ordered": ordered, "items": items})
            continue

        # Paragraph: until a blank line or the start of another block.
        para = [line.strip()]
        i += 1
        while i < n and lines[i].strip() and not is_block_start(lines[i]):
            para.append(lines[i].strip())
            i += 1
        blocks.append({"type": "paragraph", "text": " ".join(para)})
    return blocks


def split_row(line):
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|"):
        s = s[:-1]
    return [c.strip() for c in s.split("|")]


