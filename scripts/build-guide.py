def indent(text, spaces):
    """Indent the markup for readability, leaving the lines inside <pre> as they are."""
    pad = " " * spaces
    out = []
    in_pre = False
    for line in text.split("\n"):
        out.append(line if (in_pre or not line) else pad + line)
        if "<pre>" in line:
            in_pre = True
        if "</pre>" in line:
            in_pre = False
    return "\n".join(out)


def chapters_html(sections, current_file):
    items = []
    items.append('            <li class="intro-link%s"><a href="index.html">Introduction</a></li>' % (" current" if current_file == "index.html" else ""))
    for k, s in enumerate(sections, 1):
        cls = ' class="current"' if s["file"] == current_file else ""
        items.append('            <li%s><a href="%s"><span>%d</span>%s</a></li>' % (
            cls, s["file"], k, html.escape(s["title"], quote=False)))
    return """        <details class="chapters">
          <summary>Chapters</summary>
          <ol>
%s
          </ol>
        </details>""" % "\n".join(items)


def pager_html(prev, nxt):
    parts = []
    if prev:
        parts.append('            <a class="prev" href="%s"><small>Previous</small>%s</a>' % (prev["file"], html.escape(prev["title"], quote=False)))
    if nxt:
        parts.append('            <a class="next" href="%s"><small>Next</small>%s</a>' % (nxt["file"], html.escape(nxt["title"], quote=False)))
    return '          <nav class="pager" aria-label="Previous and next">\n%s\n          </nav>' % "\n".join(parts)


def last_updated(md_path):
    """The day the Markdown last changed: its last commit, or else its modification time."""
    directory = os.path.dirname(os.path.abspath(md_path)) or "."
    try:
        out = subprocess.run(
            ["git", "-C", directory, "log", "-1", "--format=%cs", "--", os.path.basename(md_path)],
            capture_output=True, text=True, timeout=20)
        day = out.stdout.strip()
        if out.returncode == 0 and re.match(r"^\d{4}-\d{2}-\d{2}$", day):
            date = datetime.date.fromisoformat(day)
            return "%s %d, %d" % (date.strftime("%B"), date.day, date.year)
    except (OSError, subprocess.SubprocessError):
        pass
    date = datetime.date.fromtimestamp(os.path.getmtime(md_path))
    return "%s %d, %d" % (date.strftime("%B"), date.day, date.year)


