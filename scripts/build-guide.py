def slugify(text):
    s = text.lower()
    s = re.sub(r"[’']", "", s)
    s = re.sub(r"[^a-z0-9\s-]", "", s)
    s = re.sub(r"\s+", "-", s.strip())
    s = re.sub(r"-{2,}", "-", s)
    return s


def render_blocks(blocks, linker, page_slug, depth=0):
    parts = []
    for b in blocks:
        t = b["type"]
        if t == "heading":
            level = min(max(b["level"], 3), 6)  # a section's own heading is the page's h2
            slug = slugify(b["text"])
            parts.append('<h%d id="%s">%s</h%d>' % (level, slug, render_inline(b["text"], linker), level))
            for shot in SCREENSHOTS.get(b["text"], []):
                parts.append("<!-- PLACEHOLDER: replace with a screenshot of %s. -->" % shot)
        elif t == "paragraph":
            parts.append("<p>" + render_inline(b["text"], linker) + "</p>")
        elif t == "code":
            parts.append("<pre><code>" + html.escape(b["text"], quote=False) + "</code></pre>")
        elif t == "table":
            head = "".join("<th>%s</th>" % render_inline(c, linker) for c in b["header"])
            body = "".join(
                "<tr>" + "".join("<td>%s</td>" % render_inline(c, linker) for c in row) + "</tr>"
                for row in b["rows"])
            parts.append('<div class="table-wrap"><table><thead><tr>%s</tr></thead><tbody>%s</tbody></table></div>' % (head, body))
        elif t == "list":
            tag = "ol" if b["ordered"] else "ul"
            items = []
            for item in b["items"]:
                if item and item[0]["type"] == "paragraph":
                    first = render_inline(item[0]["text"], linker)
                    rest = render_blocks(item[1:], linker, page_slug, depth + 1)
                else:
                    first = ""
                    rest = render_blocks(item, linker, page_slug, depth + 1)
                items.append("<li>" + first + ("\n" + rest if rest else "") + "</li>")
            parts.append("<%s>\n%s\n</%s>" % (tag, "\n".join(items), tag))
    return "\n".join(parts)


def first_text(blocks, linker):
    """The first sentence or two of a section, as plain text, for the meta description."""
    for b in blocks:
        if b["type"] == "paragraph":
            text = render_inline(b["text"], linker, plain=True)
            break
        if b["type"] == "list" and b["items"] and b["items"][0] and b["items"][0][0]["type"] == "paragraph":
            text = render_inline(b["items"][0][0]["text"], linker, plain=True)
            break
    else:
        return ""
    text = re.sub(r"\s+", " ", text).strip()
    if text.endswith(":"):
        text = text[:-1] + "."
    if len(text) <= 160:
        return text
    cut = text[:160]
    # End at the last sentence end if there is one, otherwise at the last word.
    m = re.search(r"^(.{60,}?[.!?])\s", cut + " ")
    if m and m.group(1):
        return m.group(1)
    return cut.rsplit(" ", 1)[0].rstrip(",;:") + "…"


