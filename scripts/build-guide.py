def split_sections(blocks):
    """The intro (blocks before the first '## ') and a list of sections."""
    title = None
    intro = []
    sections = []
    current = None
    for b in blocks:
        if b["type"] == "heading" and b["level"] == 1 and title is None and current is None:
            title = b["text"]
            continue
        if b["type"] == "heading" and b["level"] == 2:
            current = {"title": b["text"], "slug": slugify(b["text"]), "blocks": []}
            current["file"] = current["slug"] + ".html"
            sections.append(current)
            continue
        (current["blocks"] if current else intro).append(b)
    return title, intro, sections


def main(argv):
    ap = argparse.ArgumentParser(description="Build the User's Guide pages from the Markdown guide.")
    ap.add_argument("markdown", help="path to UserGuide.md")
    ap.add_argument("--out", help="output folder (default: guide/ in the site's root)")
    args = ap.parse_args(argv)

    site_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_dir = args.out or os.path.join(site_root, "guide")
    os.makedirs(out_dir, exist_ok=True)

    with open(args.markdown, encoding="utf-8") as f:
        lines = f.read().split("\n")
    blocks = parse_blocks(lines)
    title, intro, sections = split_sections(blocks)
    if not title or not sections:
        sys.exit("The Markdown needs a '# ' title and at least one '## ' section.")
    updated = last_updated(args.markdown)

    linker = Linker()
    for s in sections:
        linker.anchors[s["slug"]] = (s["file"], True)
        for b in s["blocks"]:
            if b["type"] == "heading":
                linker.anchors.setdefault(slugify(b["text"]), (s["file"], False))

    written = []

    # The introduction and the table of contents.
    toc = "\n".join(
        '<li><a href="%s"><span>%d</span>%s</a></li>' % (s["file"], k, html.escape(s["title"], quote=False))
        for k, s in enumerate(sections, 1))
    body = render_blocks(intro, linker, "index")
    body += '\n<h2 id="contents">Contents</h2>\n<ol class="toc">\n%s\n</ol>' % toc
    first = sections[0]
    index_html = page_html(
        file="index.html", title=title, description=first_text(intro, linker),
        eyebrow="BigBrain System Visualizer &middot; User&#8217;s Guide",
        body=body, chapters_html=chapters_html(sections, "index.html"),
        pager_html=pager_html(None, first), updated=updated)
    write(os.path.join(out_dir, "index.html"), index_html)
    written.append("index.html")

    # One page per section.
    for k, s in enumerate(sections):
        prev = sections[k - 1] if k > 0 else {"file": "index.html", "title": "Introduction"}
        nxt = sections[k + 1] if k + 1 < len(sections) else None
        body = '<div class="section-label">Chapter %d of %d</div>\n' % (k + 1, len(sections))
        body += '<h2 id="%s">%s</h2>\n' % (s["slug"], render_inline(s["title"], linker))
        for shot in SCREENSHOTS.get(s["title"], []):
            body += "<!-- PLACEHOLDER: replace with a screenshot of %s. -->\n" % shot
        body += render_blocks(s["blocks"], linker, s["slug"])
        eyebrow = '<a href="index.html">User&#8217;s Guide</a> &middot; Chapter %d of %d' % (k + 1, len(sections))
        html_text = page_html(
            file=s["file"], title=s["title"], description=first_text(s["blocks"], linker),
            eyebrow=eyebrow, body=body, chapters_html=chapters_html(sections, s["file"]),
            pager_html=pager_html(prev, nxt), updated=updated)
        write(os.path.join(out_dir, s["file"]), html_text)
        written.append(s["file"])

    # Remove pages this script wrote earlier for sections that no longer exist.
    for name in sorted(os.listdir(out_dir)):
        if name.endswith(".html") and name not in written:
            path = os.path.join(out_dir, name)
            with open(path, encoding="utf-8") as f:
                head = f.read(4000)
            if GENERATED_MARK in head:
                os.remove(path)
                print("removed stale page", name)

    unused_shots = sorted(set(SCREENSHOTS) - {s["title"] for s in sections}
                          - {b["text"] for s in sections for b in s["blocks"] if b["type"] == "heading"})
    print("wrote %d pages to %s (last updated %s)" % (len(written), out_dir, updated))
    for url in sorted(set(linker.unresolved)):
        print("note: link kept as text, no page for it on this site:", url)
    for h in unused_shots:
        print("note: no heading for screenshot placeholder:", h)


def write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
