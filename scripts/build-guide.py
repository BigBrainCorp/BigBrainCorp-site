# Inline rendering
# ---------------------------------------------------------------------------

RE_CODE_SPAN = re.compile(r"`([^`]+)`")
RE_BOLD = re.compile(r"\*\*(.+?)\*\*")
RE_LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


class Linker:
    """Resolves the Markdown's links to the pages of the guide."""

    def __init__(self):
        self.anchors = {}   # slug -> (page file, is top-level section)
        self.unresolved = []

    def href(self, url, text):
        if url.startswith("#"):
            slug = url[1:]
            target = self.anchors.get(slug)
            if target is None:
                self.unresolved.append(url)
                return None
            page, top = target
            return page if top else page + "#" + slug
        if url.endswith(".md"):
            if url in DOC_LINKS:
                return DOC_LINKS[url]
            self.unresolved.append(url)
            return None
        return url


def render_inline(text, linker, plain=False):
    """Render inline Markdown to HTML; with plain=True, to text without markup."""
    out = []
    pos = 0
    for m in RE_CODE_SPAN.finditer(text):
        out.append(render_text(text[pos:m.start()], linker, plain))
        code = m.group(1)
        out.append(code if plain else "<code>" + html.escape(code, quote=False) + "</code>")
        pos = m.end()
    out.append(render_text(text[pos:], linker, plain))
    return "".join(out)


def render_text(text, linker, plain):
    if plain:
        text = RE_LINK.sub(lambda m: m.group(1), text)
        text = RE_BOLD.sub(lambda m: m.group(1), text)
        return text
    escaped = html.escape(text, quote=False)

    def link(m):
        label, url = m.group(1), html.unescape(m.group(2))
        href = linker.href(url, label)
        if href is None:
            return label
        return '<a href="%s">%s</a>' % (html.escape(href, quote=True), label)

    escaped = RE_LINK.sub(link, escaped)
    escaped = RE_BOLD.sub(lambda m: "<strong>" + m.group(1) + "</strong>", escaped)
    return escaped


